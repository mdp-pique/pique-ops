-- Ask Pique on the public booking site (mdp-pique/pique-direct): every guest
-- conversation is kept so the team can read what guests ask.
-- Additive only. The website never gets a key that can read or change anything
-- else: it calls record_website_chat_turn() with the public anon key plus a
-- shared secret, and the function checks the secret against a stored hash.

create table public.website_chats (
  id uuid primary key,                         -- generated by the website per conversation
  started_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  page_url text,                               -- page the chat was opened on
  property_id text,                            -- Hospitable property id when opened on a home's page
  message_count integer not null default 0,
  handed_off boolean not null default false,   -- the assistant offered call / text
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.website_chats is 'Ask Pique conversations from the public booking site. Written only through record_website_chat_turn().';

create table public.website_chat_messages (
  id bigint generated always as identity primary key,
  chat_id uuid not null constraint website_chat_messages_chat_id_fkey references public.website_chats(id) on delete cascade,
  role text not null check (role in ('guest', 'assistant')),
  content text not null,
  tools jsonb,                                 -- tools the assistant used for this answer (names + inputs)
  created_at timestamptz not null default now()
);
create index website_chat_messages_chat_id_idx on public.website_chat_messages (chat_id, id);
create index website_chats_last_message_at_idx on public.website_chats (last_message_at desc);

-- One row: sha256 (hex) of the website's WEBSITE_CHAT_SECRET. Set by hand, never in a migration.
create table public.website_chat_settings (
  id integer primary key default 1 check (id = 1),
  secret_sha256 text
);
insert into public.website_chat_settings (id) values (1);

alter table public.website_chats enable row level security;
alter table public.website_chat_messages enable row level security;
alter table public.website_chat_settings enable row level security;

-- Staff with a Pique Ops profile can read conversations (same rule as slack_assistant_threads).
create policy website_chats_read on public.website_chats for select to authenticated
  using (exists (select 1 from profiles p where p.id = auth.uid()));
create policy website_chat_messages_read on public.website_chat_messages for select to authenticated
  using (exists (select 1 from profiles p where p.id = auth.uid()));
-- website_chat_settings: no policies, service role only.

create or replace function public.record_website_chat_turn(p_secret text, p_chat jsonb, p_messages jsonb)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_hash text;
  v_chat uuid := (p_chat->>'id')::uuid;
  v_count integer;
  m jsonb;
begin
  select secret_sha256 into v_hash from website_chat_settings where id = 1;
  if v_hash is null or p_secret is null or encode(digest(p_secret, 'sha256'), 'hex') <> v_hash then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if jsonb_typeof(p_messages) <> 'array' or jsonb_array_length(p_messages) > 4 then
    raise exception 'bad messages';
  end if;

  insert into website_chats (id, page_url, property_id)
  values (v_chat, left(p_chat->>'page_url', 500), left(p_chat->>'property_id', 64))
  on conflict (id) do nothing;

  select message_count into v_count from website_chats where id = v_chat for update;
  if v_count >= 200 then
    return; -- runaway conversation: stop storing, the website caps turns well below this
  end if;

  for m in select * from jsonb_array_elements(p_messages) loop
    insert into website_chat_messages (chat_id, role, content, tools)
    values (v_chat, m->>'role', left(coalesce(m->>'content', ''), 8000), case when m ? 'tools' then m->'tools' end);
  end loop;

  update website_chats
     set message_count = message_count + jsonb_array_length(p_messages),
         last_message_at = now(),
         updated_at = now(),
         handed_off = handed_off or coalesce((p_chat->>'handed_off')::boolean, false)
   where id = v_chat;
end;
$$;

revoke execute on function public.record_website_chat_turn(text, jsonb, jsonb) from public, authenticated;
grant execute on function public.record_website_chat_turn(text, jsonb, jsonb) to anon, service_role;
